async function connectDatabase() {
  if (database) return database;
  await client.connect();
  database = client.db(dbName);

  await database.collection("books").createIndex({ id: 1 }, { unique: true });
  await database.collection("users").createIndex({ id: 1 }, { unique: true });
  await database.collection("users").createIndex({ email: 1 }, { unique: true });
  await database.collection("activity").createIndex({ timestamp: -1 });
  await database.collection("loans").createIndex({ userId: 1, returnedAt: 1 });
  await database.collection("loans").createIndex({ bookId: 1, returnedAt: 1 });
  await database.collection("reviews").createIndex({ bookId: 1, userId: 1 }, { unique: true });

  const booksCollection = database.collection("books");
  const bookCount = await booksCollection.countDocuments();
  if (bookCount !== 100) {
    await booksCollection.deleteMany({});
    await booksCollection.insertMany(seedBooks);
  }

  if (await database.collection("users").countDocuments() === 0) {
    const now = new Date().toISOString();
    await database.collection("users").insertMany([
      { id: "u1", name: "Admin", email: "admin@library.demo", passwordHash: bcrypt.hashSync("admin123", 10), role: "admin", createdAt: now, lastLoginAt: null },
      { id: "u2", name: "Member", email: "member@library.demo", passwordHash: bcrypt.hashSync("member123", 10), role: "member", createdAt: now, lastLoginAt: null },
    ]);
  }

  return database;
}

function getDb() {
  if (!database) throw new Error("Database has not been connected");
  return database;
}

